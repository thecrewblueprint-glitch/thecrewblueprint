import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { lightingCourses as courseMetadata } from './course-data-lighting.mjs';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.join(scriptDir, 'course-data-lighting.mjs');

function acceptedFile(relativePath) {
  return execFileSync('git', ['show', `origin/main:${relativePath}`], {
    cwd: path.resolve(scriptDir, '..'),
    encoding: 'utf8'
  });
}

function text(html) {
  return html
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&middot;/g, '·')
    .replace(/&mdash;/g, '—')
    .replace(/&rsquo;/g, '’')
    .replace(/\s+/g, ' ')
    .trim();
}

function lightingOneModules(html) {
  const moduleMatch = html.match(/const modules = (\[[\s\S]*?\n\]);/);
  if (!moduleMatch) throw new Error('Could not read Lighting 1 module map.');
  const moduleMap = Function(`"use strict"; return (${moduleMatch[1]});`)();
  const rendered = new Map();
  for (const match of html.matchAll(/function renderL(\d+)\(\)\{\s*return `([\s\S]*?)`;\s*\}/g)) {
    rendered.set(match[1], match[2]);
  }
  return moduleMap.map((module) => ({
    name: module.name || module.title,
    lessons: module.lessons.map((lesson) => {
      const key = lesson.id.replace('.', '');
      const raw = rendered.get(key);
      if (!raw) throw new Error(`Could not read Lighting 1 lesson ${lesson.id}.`);
      return { name: lesson.name, objective: lesson.obj, blocks: [{ type: 'html', html: raw }] };
    })
  }));
}

function lightingTwoModules(html) {
  const starts = [...html.matchAll(/<div id="lesson-(\d+)" class="lesson-content"[^>]*>/g)];
  if (starts.length !== 6) throw new Error(`Expected six Lighting 2 lessons, found ${starts.length}.`);
  const lessons = starts.map((match, index) => {
    const start = match.index + match[0].length;
    const end = index + 1 < starts.length ? starts[index + 1].index : html.indexOf('<script>', start);
    let raw = html.slice(start, end).replace(/\s*<\/div>\s*$/, '').trim();
    const titleMatch = raw.match(/<h1>([\s\S]*?)<\/h1>/);
    const objectiveMatch = raw.match(/<div class="rule"[^>]*>([\s\S]*?)<\/div>/);
    if (!titleMatch || !objectiveMatch) throw new Error(`Could not read Lighting 2 lesson ${index + 1}.`);
    const name = text(titleMatch[1]);
    const objective = text(objectiveMatch[1]);
    raw = raw
      .replace(/\s*<h1>[\s\S]*?<\/h1>/, '')
      .replace(/\s*<div class="card progress">[\s\S]*?<div class="rule"[\s\S]*?<\/div>\s*<\/div>/, '')
      .trim();
    return { name, objective, blocks: [{ type: 'html', html: raw }] };
  });
  return [{ name: 'Production Flow', lessons }];
}

const lightingOne = {
  ...courseMetadata[0],
  inlineAssessment: true,
  modules: lightingOneModules(acceptedFile('courses/pathway-lighting-01-support.html'))
};
const lightingTwo = {
  ...courseMetadata[1],
  inlineAssessment: true,
  modules: lightingTwoModules(acceptedFile('courses/pathway-lighting-02-production-flow.html'))
};

await writeFile(
  outputPath,
  `// Generated by scripts/migrate-lighting-to-shared-shell.mjs from accepted pre-migration course content.\nexport const lightingCourses = ${JSON.stringify([lightingOne, lightingTwo], null, 2)};\n`,
  'utf8'
);

console.log('Preserved Lighting 1 and Lighting 2 content in the shared course data model.');
